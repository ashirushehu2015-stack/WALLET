$rootDir = Split-Path -Path (Split-Path -Path $PSScriptRoot -Parent) -Parent

foreach ($r in $reports) {
  $md = Join-Path -Path $rootDir -ChildPath "$r.md"
  $docx = Join-Path -Path $rootDir -ChildPath "$r.docx"
  if (Test-Path $md) {
    Write-Host "Converting $r.md to $r.docx..."
    & "$PSScriptRoot\convert-remediation-docx.ps1" -mdFile $md -docxFile $docx
  } else {
    Write-Warning "File not found: $md"
  }
}
